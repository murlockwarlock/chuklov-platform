export function portalText(
    locale: PortalLocale | string | undefined,
    key: string,
    values: Record<string, string | number> = {},
): string {
    const selectedLocale: PortalLocale = locale === 'en' ? 'en' : 'ru';
    const template = messages[selectedLocale][key] ?? messages.ru[key] ?? key;

    return Object.entries(values).reduce(
        (text, [name, value]) => text.replaceAll('{' + name + '}', String(value)),
        template,
    );
}
